/// `htmlCheckAutoClose`: does start tag `new` implicitly close `open`?
pub(crate) fn closes(new: &str, open: &str) -> bool {
    START_CLOSE.binary_search(&(open, new)).is_ok()
}

/// `htmlGetEndPriority`: end tags only close elements of lower or equal priority.
pub(crate) fn end_priority(name: &str) -> u8 {
    match name {
        "div" => 150,
        "td" | "th" => 160,
        "tr" => 170,
        "thead" | "tbody" | "tfoot" => 180,
        "table" => 190,
        "head" | "body" => 200,
        "html" => 220,
        _ => 100,
    }
}

