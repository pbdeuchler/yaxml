/// `htmlTagLookup`: ASCII case-insensitive.
pub(crate) fn element(name: &str) -> Option<&'static Element> {
    ELEMENTS
        .binary_search_by(|entry| {
            let bytes = name.bytes().map(|byte| byte.to_ascii_lowercase());
            entry.name.bytes().cmp(bytes)
        })
        .ok()
        .map(|index| &ELEMENTS[index])
}

