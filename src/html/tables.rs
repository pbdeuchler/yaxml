//! Data tables ported from libxml2 2.15.4: `HTMLparser.c` (html40ElementTable,
//! htmlStartClose, htmlEndPriority, allowPCData, html40EntitiesTable),
//! `HTMLtree.c` (htmlIsBooleanAttr). Charsets come from `crate::encoding`. Entries
//! keep upstream order; lookups binary-search tables that upstream bsearches.

/// Content model of an element's text, `endCheckState` in libxml2.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(crate) enum Mode {
    Data,
    Rcdata,
    Rawtext,
    Plaintext,
    Script,
    ScriptEsc1,
    ScriptEsc2,
}

impl Mode {
    /// Text in these modes becomes CDATA nodes and serializes unescaped.
    pub(crate) fn raw(self) -> bool {
        !matches!(self, Self::Data | Self::Rcdata)
    }
}

/// The parts of `htmlElemDesc` that 2.15.4 still consults.
pub(crate) struct Element {
    pub(crate) name: &'static str,
    /// 1: may be omitted, 2: forbidden, 3: stylistic (closes easily).
    pub(crate) end_tag: u8,
    pub(crate) empty: bool,
    pub(crate) inline: bool,
    pub(crate) mode: Mode,
}

const fn el(name: &'static str, end_tag: u8, empty: bool, inline: bool, mode: Mode) -> Element {
    Element {
        name,
        end_tag,
        empty,
        inline,
        mode,
    }
}

