#!/usr/bin/env -S uv run --no-project
"""Generate src/encoding/iconv.rs from the system iconv (macOS libiconv).

Usage: uv run --no-project tooling/gen_iconv.py > src/encoding/iconv.rs
       cargo fmt

The code pages are the EBCDIC ones `iconv -l` lists on macOS, which the
iconv-enabled libxml2 2.15.4 oracle decodes, and the UCS-4 labels it writes
(machine-order INTERNAL/SWAPPED aside); labels are iconv's aliases. Entries
map every byte; zero marks a byte iconv rejects.
"""
import subprocess

# iconv lists these in one group; their byte orders as xmllint --encode writes
# them (UTF-32 is big-endian behind a BOM). libxml2 claims "UCS4" itself and fails.
UCS4 = {
    "None": ["UTF-32"],
    "Some(false)": ["CSUCS4", "ISO-10646-UCS-4", "UCS-4", "UCS-4BE", "UTF-32BE", "UTF32BE"],
    "Some(true)": ["UCS-4LE", "UTF-32LE", "UTF32LE"],
}
PAGES = ["037", "273", "277", "278", "280", "284", "285", "297", "424", "500", "871", "875", "1026"]


def scalar(page, byte):
    run = subprocess.run(
        ["iconv", "-f", f"CP{page}", "-t", "UTF-32BE"], input=bytes([byte]), capture_output=True
    )
    return int.from_bytes(run.stdout, "big") if run.returncode == 0 and len(run.stdout) == 4 else 0


aliases = {}
for line in subprocess.run(["iconv", "-l"], capture_output=True, text=True).stdout.splitlines():
    names = line.split()
    for page in PAGES:
        if f"CP{page}" in names:
            aliases[page] = names

print("// @generated by tooling/gen_iconv.py from the macOS iconv.")
print("// EBCDIC entries map bytes 0x00..=0xFF; zero marks a byte iconv rejects.")
print("// UCS-4 labels only name output: UCS-4 input is detected, its label ignored.")
print()
print("use super::Charset::{self, Ebcdic, Ucs4};")
for page in PAGES:
    values = [scalar(page, b) for b in range(256)]
    print()
    print(f"pub(super) const CP{page}: [u16; 256] = [")
    for row in range(0, 256, 8):
        print("    " + " ".join(f"0x{v:04x}," for v in values[row : row + 8]))
    print("];")
labels = sorted(
    [(name.lower(), f"Ebcdic(&CP{page})") for page in PAGES for name in aliases[page]]
    + [(name.lower(), f"Ucs4({order})") for order, names in UCS4.items() for name in names]
)
print()
print(f"pub(super) const LABELS: [(&str, Charset); {len(labels)}] = [")
for name, kind in labels:
    print(f'    ("{name}", {kind}),')
print("];")
