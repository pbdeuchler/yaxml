#!/usr/bin/env python3
"""Regenerate src/html/entities.rs from libxml2 2.15.4 codegen/html5ent.inc.

The C file is a prefix trie over the WHATWG entities.json names that end in
';'. Each record carries a flag saying whether the name is also valid without
the semicolon (a "legacy" reference). This script flattens the trie back into
a sorted (name, legacy, replacement) table.

Usage: python3 tooling/html_entities.py path/to/html5ent.inc > src/html/entities.rs
"""

import re
import sys

ENT_F_SEMICOLON = 0x80
ENT_F_SUBTABLE = 0x40


def table(source, name):
    body = re.search(r"%s\[\d+\] = \{(.*?)\};" % name, source, re.S).group(1)
    values = []
    for token in re.findall(r"'(?:[^'\\]|\\.)'|\d+", body):
        values.append(ord(token[1]) if token.startswith("'") else int(token))
    return values


def main(path):
    source = open(path, encoding="ascii").read()
    alpha = table(source, "htmlEntAlpha")
    values = table(source, "htmlEntValues")
    strings = table(source, "htmlEntStrings")
    entries = []

    def walk(left, right, prefix):
        for index in range(left, right):
            record = values[index]
            head = strings[record]
            length = head & ~(ENT_F_SEMICOLON | ENT_F_SUBTABLE)
            name = prefix + bytes(strings[record + 1 : record + 1 + length]).decode()
            cursor = record + 1 + length
            subtable = None
            if head & ENT_F_SUBTABLE:
                subtable = (index + strings[cursor], strings[cursor + 1])
                cursor += 2
            replacement = bytes(strings[cursor + 1 : cursor + 1 + strings[cursor]])
            entries.append((name, bool(head & ENT_F_SEMICOLON), replacement.decode()))
            if subtable is not None:
                walk(subtable[0], subtable[0] + subtable[1], name)

    for first in range(len(alpha) // 3):
        start = alpha[first * 3] | alpha[first * 3 + 1] << 8
        count = alpha[first * 3 + 2]
        if count:
            walk(start, start + count, chr(first + 64))
    entries.sort()

    print("// Generated by tooling/html_entities.py from libxml2 2.15.4")
    print("// codegen/html5ent.inc (WHATWG entities.json). Do not edit.")
    print("//")
    print("// (name without ';', also valid without ';', replacement)")
    print("pub(super) static ENTITIES: [(&str, bool, &str); %d] = [" % len(entries))
    for name, legacy, replacement in entries:
        escaped = "".join("\\u{%x}" % ord(c) for c in replacement)
        print('    ("%s", %s, "%s"),' % (name, "true" if legacy else "false", escaped))
    print("];")


if __name__ == "__main__":
    main(sys.argv[1])
