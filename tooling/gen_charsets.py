#!/usr/bin/env python3
"""Generate src/encoding/charsets.rs from a libxml2 2.15.4 source tree.

Usage: uv run tooling/gen_charsets.py LIBXML2_SRC > src/encoding/charsets.rs
       cargo fmt

Tables come from codegen/charset.inc (xmlunicodetable_*); labels come from
xmlEncTable in encoding.c, every label with its xmlCharEncoding;
CharEncoding::builtin says which have a converter without iconv/ICU.
"""
import re
import sys

src = sys.argv[1]
inc = open(f"{src}/codegen/charset.inc").read()
enc = open(f"{src}/encoding.c").read()

tables = {"US_ASCII": [0] * 128, "ISO_8859_1": list(range(0x80, 0x100))}
for name, body in re.findall(r"xmlunicodetable_(\w+) \[128\] = \{([^}]*)\}", inc):
    tables[name.upper().replace("ISO8859", "ISO_8859")] = [
        int(v, 16) for v in re.findall(r"0x[0-9a-f]+", body)
    ]

variants = {
    "UTF8": "Utf8", "UTF16": "Utf16", "UTF16LE": "Utf16Le", "UTF16BE": "Utf16Be",
    "UCS2": "Ucs2", "UCS4LE": "Ucs4Le", "2022_JP": "Iso2022Jp", "SHIFT_JIS": "ShiftJis",
    "EUC_JP": "EucJp", "ASCII": "Ascii", "HTML": "Html", "WINDOWS_1252": "Windows1252",
}


def variant(kind):
    return f"Iso{kind}" if kind.startswith("8859_") else variants[kind]


table = re.search(r"xmlEncTable\[\] = \{(.*?)\n\};", enc, re.S).group(1)
labels = []
# libxml2 binary-searches the table; "unicodefeff" sits after "unicodefffe",
# where no bsearch finds it, so a label out of order is dropped.
for label, kind in re.findall(r'\{ "([^"]+)", XML_CHAR_ENCODING_(\w+) \}', table):
    if not labels or label > labels[-1][0]:
        labels.append((label, kind))

print("// @generated by tooling/gen_charsets.py from libxml2 2.15.4")
print("// codegen/charset.inc (xmlunicodetable_*) and encoding.c (xmlEncTable).")
print("// Entries map bytes 0x80..=0xFF; zero marks a byte libxml2 rejects.")
print("// libxml2 maps iso8859-10/13/14/15 to ISO-8859-1; this is preserved.")
print("// Labels are sorted for a binary search; libxml2 never finds unicodefeff.")
print()
print("use super::CharEncoding as E;")
for name in sorted(tables, key=lambda n: (len(n), n)):
    values = tables[name]
    assert len(values) == 128, name
    print()
    if not any(values):
        print(f"pub(super) const {name}: [u16; 128] = [0; 128];")
        continue
    print(f"pub(super) const {name}: [u16; 128] = [")
    for row in range(0, 128, 8):
        print("    " + " ".join(f"0x{v:04x}," for v in values[row : row + 8]))
    print("];")
print()
print(f"pub(super) const LABELS: [(&str, E); {len(labels)}] = [")
for label, kind in labels:
    print(f'    ("{label}", E::{variant(kind)}),')
print("];")
