#!/usr/bin/env python3
"""Generate src/regexp/unicode.rs from a libxml2 2.15.4 source tree.

Usage: uv run tooling/gen_unicode.py LIBXML2_SRC > src/regexp/unicode.rs
       cargo fmt

Categories and blocks come from codegen/unicode.inc (libxml2's Unicode 4.0.1
tables, including its quirks: UnicodeData "First/Last" ranges contribute only
their two endpoints). The XML 1.0 (4th edition) Letter/Digit/Combining/Extender
classes behind \\i and \\c come from codegen/ranges.def.
"""
import re
import sys

src = sys.argv[1]
inc = open(f"{src}/codegen/unicode.inc").read()
defs = open(f"{src}/codegen/ranges.def").read()

tables = {
    name: [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+)\}", body)]
    for name, body in re.findall(r"xmlCh[SL]Range (\w+)\[\] = \{(.*?)\};", inc, re.S)
}


def group(stem):
    return tables.get(stem + "S", []) + tables.get(stem + "L", [])


categories = {}
for name, body in re.findall(r"xmlUCSIsCat(\w+)\(int code\) \{(.*?)\}\n", inc, re.S):
    inline = re.search(r"&xml(\w+)G", body)
    if inline:
        categories[name] = group("xml" + inline.group(1))
    else:
        categories[name] = [
            (int(a or c, 16), int(b or c, 16))
            for a, b, c in re.findall(
                r"code >= (0x[0-9a-f]+)\) && \(code <= (0x[0-9a-f]+)|code == (0x[0-9a-f]+)", body
            )
        ]
categories["Cn"] = []  # libxml2: "doesn't exist anymore", never matches

blocks = []
for name, short, long in re.findall(r'\{"([^"]+)",\s*\{\d+,\d+,(\w+),(\w+)\}\}', inc):
    blocks.append((name, tables.get(short, []) + tables.get(long, [])))
assert blocks == sorted(blocks, key=lambda b: b[0].encode()), "blocks must be strcmp-sorted"


def chvalid(name):
    body = re.search(rf"name {name}\n(.*?)\nend", defs, re.S).group(1)
    out = []
    for lo, hi in re.findall(r"(0x[0-9A-Fa-f]+|'.')(?:\.\.(0x[0-9A-Fa-f]+|'.'))?", body):
        value = lambda v: ord(v[1]) if v.startswith("'") else int(v, 16)
        out.append((value(lo), value(hi or lo)))
    return out


def merge(ranges):
    out = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(hi, out[-1][1]))
        else:
            out.append((lo, hi))
    return out


letter = chvalid("xmlIsBaseChar") + chvalid("xmlIsIdeographic")
init_name = merge(letter + [(0x5F, 0x5F), (0x3A, 0x3A)])
name_char = merge(
    letter + chvalid("xmlIsDigit") + chvalid("xmlIsCombining") + chvalid("xmlIsExtender") + [(c, c) for c in b".-_:"]
)
not_word = merge(categories["P"] + categories["Z"] + categories["C"])


def table(ranges):
    return "&[" + ", ".join(f"(0x{a:x}, 0x{b:x})" for a, b in merge(ranges)) + "]"


print("//! Character tables for XML Schema regular expressions.")
print("//!")
print("//! Generated by `tooling/gen_unicode.py` from libxml2 2.15.4")
print("//! `codegen/unicode.inc` (Unicode 4.0.1, as libxml2 ships it) and")
print("//! `codegen/ranges.def`. Do not edit by hand.")
print()
print("/// General categories by name, sorted.")
print("pub(super) const CATEGORIES: &[(&str, &[(u32, u32)])] = &[")
for name in sorted(categories):
    print(f'    ("{name}", {table(categories[name])}),')
print("];")
print()
print("/// `\\p{IsX}` blocks by name, in `strcmp` order.")
print("pub(super) const BLOCKS: &[(&str, &[(u32, u32)])] = &[")
for name, ranges in blocks:
    print(f'    ("{name}", {table(ranges)}),')
print("];")
print()
print("/// `\\i`: XML 1.0 (4th edition) Letter, `_` and `:`.")
print(f"pub(super) const INIT_NAME: &[(u32, u32)] = {table(init_name)};")
print()
print("/// `\\c`: XML 1.0 (4th edition) NameChar.")
print(f"pub(super) const NAME_CHAR: &[(u32, u32)] = {table(name_char)};")
print()
print("/// `\\W`: categories P, Z and C.")
print(f"pub(super) const NOT_WORD: &[(u32, u32)] = {table(not_word)};")
